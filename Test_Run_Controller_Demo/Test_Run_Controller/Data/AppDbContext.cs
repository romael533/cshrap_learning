using Microsoft.EntityFrameworkCore;
using Test_Run_Controller.Controllers;

namespace Test_Run_Controller.Data
{
    public class AppDbContext : DbContext
    {
        public AppDbContext(DbContextOptions<AppDbContext> options) : base(options) { }

        public DbSet<TestResult> TestResults => Set<TestResult>();

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<TestResult>(e =>
            {
                e.ToTable("posttes");                       // table name from your request; change if needed
                e.HasKey(t => t.Id);                        // Id is generated by the database
                e.Property(t => t.Status).HasConversion<string>(); // store Passed/Failed as text
            });
        }

    }
}
